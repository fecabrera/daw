    pub fn unit(self) -> &'static str {
        let key = self.info().key;
        if key.ends_with("frequency") {
            "Hz"
        } else if key.ends_with("attack") || key.ends_with("release") {
            "ms"
        } else if key.ends_with("ratio") {
            ":1"
        } else if key == "dry_wet" {
            "%"
        } else if key.ends_with("threshold")
            || key.ends_with("makeup")
            || key.ends_with("knee")
            || key == "level"
        {
            "dB"
        } else {
            ""
        }
    }
    pub fn format(self, value: f64) -> Result<String, ParameterError> {
        self.validate(value)?;
        Ok(if self.info().scale == Scale::Boolean {
            if value == 0.0 {
                "Off".into()
            } else {
                "On".into()
            }
        } else if self.info().key.ends_with("detection") {
            ["Peak", "RMS"][value as usize].into()
        } else if self.info().scale == Scale::Gain {
            format!("{} dB", gain::format_db(value))
        } else if self == Self::DryWet {
            format!("{:.3}%", value * 100.0)
        } else {
            format!("{value:.4} {}", self.unit())
        })
    }
    pub fn parse(self, text: &str) -> Result<f64, ParameterError> {
        let text = text.trim().to_lowercase();
        let v = if self.info().scale == Scale::Gain {
            gain::parse_db(&text).ok_or(ParameterError)?
        } else if self.info().scale == Scale::Boolean {
            match text.as_str() {
                "on" | "1" => 1.0,
                "off" | "0" => 0.0,
                _ => return Err(ParameterError),
            }
        } else if self.info().key.ends_with("detection") {
            match text.as_str() {
                "peak" | "0" => 0.0,
                "rms" | "1" => 1.0,
                _ => return Err(ParameterError),
            }
        } else {
            let unit = self.unit().to_lowercase();
            let text = text.strip_suffix(&unit).unwrap_or(&text).trim();
            text.parse::<f64>().map_err(|_| ParameterError)?
                / if self == Self::DryWet { 100.0 } else { 1.0 }
        };
        self.validate(v)
    }
