    pub fn unit(self) -> &'static str {
        if self == Self::Level {
            return "dB";
        }
        if self == Self::Bypass {
            return "";
        }
        match (self.index() - 1) % 5 {
            2 => "Hz",
            3 => "dB",
            4 => "Q",
            _ => "",
        }
    }
    pub fn format(self, value: f64) -> Result<String, ParameterError> {
        self.validate(value)?;
        let info = self.info();
        Ok(if info.scale == Scale::Boolean {
            if value == 0.0 { "Off" } else { "On" }.into()
        } else if self != Self::Level && (self.index() - 1) % 5 == 1 {
            daw_unit_core::EqBandMode::ALL[value as usize]
                .label()
                .into()
        } else if info.scale == Scale::Gain {
            format!("{} dB", gain::format_db(value))
        } else {
            format!("{value:.3} {}", self.unit())
        })
    }
    pub fn parse(self, text: &str) -> Result<f64, ParameterError> {
        let text = text.trim().to_lowercase();
        let info = self.info();
        let value = if info.scale == Scale::Boolean {
            match text.as_str() {
                "off" | "0" => 0.0,
                "on" | "1" => 1.0,
                _ => return Err(ParameterError),
            }
        } else if self != Self::Level && (self.index() - 1) % 5 == 1 {
            daw_unit_core::EqBandMode::ALL
                .into_iter()
                .position(|m| m.label().to_lowercase() == text)
                .map(|i| i as f64)
                .or_else(|| text.parse().ok())
                .ok_or(ParameterError)?
        } else if info.scale == Scale::Gain {
            gain::parse_db(&text).ok_or(ParameterError)?
        } else {
            text.strip_suffix(&self.unit().to_lowercase())
                .unwrap_or(&text)
                .trim()
                .parse()
                .map_err(|_| ParameterError)?
        };
        self.validate(value)
    }
